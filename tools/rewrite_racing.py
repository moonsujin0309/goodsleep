# 층 간 어휘 겹침 검사 — 한 세션에서 같은 말이 두 번 들리는 것을 막는다
OWNED = {
    "가라앉": "drift", "멀어지": "fade", "무거워지": "release",
    "숨": "breath", "어깨": "release", "소리만 남": None,
}
def audit():
    problems = []
    for word, owner in OWNED.items():
        if owner is None:
            continue
        found = [l for l in RACING["sequence"]
                 if any(word in p["text"] for p in RACING[l])]
        strays = [l for l in found if l != owner]
        if strays:
            problems.append(f"  '{word}' 는 {owner} 전용인데 {', '.join(strays)} 에도 있음")
    return problems


m = json.loads(MANIFEST.read_text(encoding="utf-8"))
m["states"]["racing"] = RACING
MANIFEST.write_text(json.dumps(m, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

pieces = sum(len(RACING[l]) for l in RACING["sequence"])
combos = 1
for l in RACING["sequence"]:
    combos *= len(RACING[l])
sents = {l: len(re.split(r"(?<=[.!?。])\s+", RACING[l][0]["text"].strip())) for l in RACING["sequence"]}
print(f"racing 교체 — 조각 {pieces}개 · 조합 {combos}개")
print("  층별 문장 수(첫 조각 기준):", ", ".join(f"{l} {n}" for l, n in sents.items()))

issues = audit()
if issues:
    print("\n어휘 겹침:")
    print("\n".join(issues))
    sys.exit(1)
