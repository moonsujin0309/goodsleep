# 층 간 어휘 겹침 검사 — rewrite_racing.py 와 같은 규칙.
# 소유 층이 없는 상태(예: nap 에 breath 없음)에서 그 말이 나오면 전부 걸린다.
OWNED = {
    "가라앉": "drift", "멀어지": "fade", "무거워지": "release",
    "숨": "breath", "어깨": "release",
}

def audit(sid, state):
    problems = []
    for word, owner in OWNED.items():
        found = [l for l in state["sequence"]
                 if any(word in p["text"] for p in state[l])]
        strays = [l for l in found if l != owner]
        if strays:
            problems.append(f"  [{sid}] '{word}' 는 {owner} 전용인데 {', '.join(strays)} 에 있음")
    return problems


m = json.loads(MANIFEST.read_text(encoding="utf-8"))
issues = []
for sid, state in STATES.items():
    m["states"][sid] = state
    issues += audit(sid, state)

    pieces = sum(len(state[l]) for l in state["sequence"])
    combos = 1
    for l in state["sequence"]:
        combos *= len(state[l])
    sents = sum(len(re.split(r"(?<=[.!?。])\s+", p["text"].strip()))
                for l in state["sequence"] for p in state[l])
    print(f"{sid:<8} 조각 {pieces:>2}개 · 조합 {combos:>3} · 문장 {sents:>3}개 · 층 {'/'.join(state['sequence'])}")

if issues:
    print("\n어휘 겹침:")
    print("\n".join(issues))
