# 층 간 어휘 겹침 검사 — rewrite_racing.py 와 같은 규칙.
# 소유 층이 없는 상태(예: nap 에 breath 없음)에서 그 말이 나오면 전부 걸린다.
# 이완이 하체(release)·상체(release2)로 갈라지면서 소유가 집합이 됐다.
# tail 은 아무 소유 어휘도 못 쓴다 — 여운은 몸도 이미지도 아니고 그저 뜸해지는 말이다.
OWNED = {
    "가라앉": {"drift"}, "멀어지": {"fade"}, "무거워지": {"release", "release2"},
    "숨": {"breath"}, "어깨": {"release", "release2"},
}

def audit(sid, state):
    problems = []
    for word, owners in OWNED.items():
        found = [l for l in state["sequence"]
                 if any(word in p["text"] for p in state.get(l, []))]
        strays = [l for l in found if l not in owners]
        if strays:
            problems.append(f"  [{sid}] '{word}' 는 {'/'.join(sorted(owners))} 전용인데 {', '.join(strays)} 에 있음")
    return problems


